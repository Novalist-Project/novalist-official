import { expect, test } from '@playwright/test'
import { launchApp, seedBook, dismissTour, resizeWindow, type Harness } from './harness'

async function openPlan(h: Harness): Promise<void> {
  await dismissTour(h.page)
  await resizeWindow(h, 1500, 900)
  await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('structure'))
  await expect(h.page.locator('.structure-board')).toBeVisible()
}

test('Structure creates empty acts, moves chapters, edits summaries and undoes a move', async () => {
  const h = await launchApp('nl-writing-planning-')
  try {
    await seedBook(h, { Arrival: ['First light'], Departure: ['Last light'] })
    await openPlan(h)
    await h.page.getByRole('button', { name: 'New act', exact: true }).click()
    const prompt = h.page.getByRole('dialog', { name: 'New act' })
    await prompt.locator('input').fill('Act One')
    await prompt.getByRole('button', { name: 'OK', exact: true }).click()
    await expect(h.page.locator('.structure-act').filter({ hasText: 'Act One' })).toBeVisible()
    const chapter = h.page.locator('.structure-chapter').filter({ has: h.page.getByRole('button', { name: 'Arrival', exact: true }) })
    await chapter.getByRole('button', { name: 'Add chapter summary' }).click()
    await chapter.getByRole('textbox', { name: 'Chapter summary' }).fill('A stranger arrives at dawn.')
    await chapter.getByRole('button', { name: 'OK', exact: true }).click()
    await expect(chapter).toContainText('A stranger arrives at dawn.')
    await chapter.getByRole('button', { name: 'Move', exact: true }).click()
    const move = h.page.getByRole('dialog', { name: 'Move' })
    await move.getByLabel('Destination').selectOption({ label: 'Act One' })
    await move.getByRole('button', { name: 'Move', exact: true }).click()
    await expect(h.page.locator('.structure-board')).toHaveAttribute('aria-busy', 'false')
    await expect.poll(async () => (await h.rpc<{ chapters: { title: string; act: string }[] }>('project/getState')).chapters.find(value => value.title === 'Arrival')?.act).toBe('Act One')
    await h.page.locator('.planning-view').getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(async () => (await h.rpc<{ chapters: { title: string; act: string }[] }>('project/getState')).chapters.find(value => value.title === 'Arrival')?.act).toBe('')
    for (const name of ['Corkboard', 'Outliner', 'Board', 'Structure']) {
      await h.page.locator('.manuscript-modes').getByRole('button', { name, exact: true }).click()
      await expect(h.page.locator('.planning-view')).toContainText('Arrival')
    }
  } finally { await h.close() }
})

test('Binder moves and chapter act edits keep groups consecutive and undo as structural actions', async () => {
  const h = await launchApp('nl-writing-binder-acts-')
  try {
    const book = await seedBook(h, { A1: ['First'], A2: ['Second'], B1: ['Third'], B2: ['Fourth'] }, 'Binder acts', false)
    for (const chapter of book.chapters) await h.rpc('project/setChapterAct', [chapter.guid, chapter.title.startsWith('A') ? 'Act A' : 'Act B'])
    expect((await h.rpc<{ issues: unknown[] }>('planning/get')).issues).toEqual([])
    await h.page.evaluate(async () => window.novalistStores.project.getState().applyState(await window.novalistRpc.request('project/getState')))
    await openPlan(h)
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('write'))
    const rows = h.page.locator('.binder-chapter-row')
    const order = () => h.page.evaluate(() => window.novalistStores.project.getState().chapters.map(chapter => `${chapter.title}:${chapter.act}`))
    await expect.poll(order).toEqual(['A1:Act A', 'A2:Act A', 'B1:Act B', 'B2:Act B'])
    await rows.filter({ hasText: 'A1' }).dragTo(rows.filter({ hasText: 'B1' }))
    await expect.poll(order).toEqual(['A2:Act A', 'B1:Act B', 'A1:Act B', 'B2:Act B'])
    await openPlan(h)
    await h.page.locator('.planning-view').getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(order).toEqual(['A1:Act A', 'A2:Act A', 'B1:Act B', 'B2:Act B'])
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('write'))
    await rows.filter({ hasText: 'B1' }).click({ button: 'right' })
    await h.page.getByRole('menuitem', { name: 'Assign act', exact: true }).click()
    const dialog = h.page.getByRole('dialog')
    await dialog.getByLabel('Act', { exact: true }).selectOption('Act A')
    await dialog.locator('.date-range-row input').first().fill('2042-03-04')
    await dialog.getByRole('button', { name: 'OK', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect.poll(order).toEqual(['A1:Act A', 'A2:Act A', 'B1:Act A', 'B2:Act B'])
    await openPlan(h)
    await h.page.locator('.planning-view').getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(order).toEqual(['A1:Act A', 'A2:Act A', 'B1:Act B', 'B2:Act B'])
    expect(await h.page.evaluate(() => window.novalistStores.project.getState().chapters.find(chapter => chapter.title === 'B1')?.dateStart)).toBe('2042-03-04')
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('write'))
    await h.page.locator('[data-command="project.newChapter"]').click()
    const create = h.page.getByRole('dialog', { name: 'New Chapter', exact: true })
    await create.locator('input.dialog-input').first().fill('Added to A')
    await create.getByLabel('Act', { exact: true }).selectOption('Act A')
    await create.locator('.date-range-row input').first().fill('2042-03-05')
    await create.getByRole('button', { name: 'OK', exact: true }).click()
    await expect(create).toHaveCount(0)
    await expect.poll(order).toEqual(['A1:Act A', 'A2:Act A', 'Added to A:Act A', 'B1:Act B', 'B2:Act B'])
    const created = await h.page.evaluate(() => window.novalistStores.project.getState().chapters.find(chapter => chapter.title === 'Added to A'))
    expect(created?.scenes).toHaveLength(1)
    expect(created?.scenes[0].wordCount).toBe(0)
    expect(created?.dateStart).toBe('2042-03-05')
    await openPlan(h)
    await h.page.locator('.planning-view').getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(order).toEqual(['A1:Act A', 'A2:Act A', 'B1:Act B', 'B2:Act B'])
    const planning = await h.rpc<{ issues: unknown[] }>('planning/get')
    expect(planning.issues).toEqual([])
  } finally { await h.close() }
})

test('chapter dialogs honor an empty act before populated acts when assigning and creating', async () => {
  const h = await launchApp('nl-writing-empty-act-')
  try {
    const book = await seedBook(h, { A1: ['First'], B1: ['Second'] }, 'Empty act', false)
    for (const chapter of book.chapters) await h.rpc('project/setChapterAct', [chapter.guid, chapter.title === 'A1' ? 'Act A' : 'Act B'])
    await h.page.evaluate(async () => window.novalistStores.project.getState().applyState(await window.novalistRpc.request('project/getState')))
    await openPlan(h)
    await h.page.getByRole('button', { name: 'New act', exact: true }).click()
    const prompt = h.page.getByRole('dialog', { name: 'New act' })
    await prompt.locator('input').fill('Early')
    await prompt.getByRole('button', { name: 'OK', exact: true }).click()
    await h.page.locator('.structure-act').filter({ hasText: 'Early' }).getByRole('button', { name: 'Move', exact: true }).click()
    const move = h.page.getByRole('dialog', { name: 'Move' })
    await move.getByLabel('Destination').selectOption({ label: 'Act A' })
    await move.getByRole('button', { name: 'Move', exact: true }).click()
    await expect(move).toHaveCount(0)
    await expect(h.page.locator('.structure-board')).toHaveAttribute('aria-busy', 'false')
    const planning = async () => {
      await expect.poll(() => h.page.evaluate(() => {
        const state = window.novalistStores.project.getState()
        return !state.workspaceBusy && !state.changingSceneStructure && state.workspaceTransitionToken === null
      })).toBe(true)
      return h.rpc<{ acts: { name: string | null; chapterGuids: string[] }[]; issues: unknown[] }>('planning/get')
    }
    await expect.poll(async () => (await planning()).acts.map(act => act.name)).toEqual(['Early', 'Act A', 'Act B'])
    const order = () => h.page.evaluate(() => window.novalistStores.project.getState().chapters.map(chapter => `${chapter.title}:${chapter.act}`))
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('write'))
    await h.page.locator('.binder-chapter-row').filter({ hasText: 'B1' }).click({ button: 'right' })
    await h.page.getByRole('menuitem', { name: 'Assign act', exact: true }).click()
    const assign = h.page.getByRole('dialog')
    await assign.getByLabel('Act', { exact: true }).selectOption('Early')
    await assign.getByRole('button', { name: 'OK', exact: true }).click()
    await expect(assign).toHaveCount(0)
    await expect.poll(order).toEqual(['B1:Early', 'A1:Act A'])
    expect((await planning()).issues).toEqual([])
    await openPlan(h)
    await h.page.locator('.planning-view').getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(order).toEqual(['A1:Act A', 'B1:Act B'])
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('write'))
    await h.page.locator('[data-command="project.newChapter"]').click()
    const create = h.page.getByRole('dialog', { name: 'New Chapter', exact: true })
    await create.locator('input.dialog-input').first().fill('New opening')
    await create.getByLabel('Act', { exact: true }).selectOption('Early')
    await create.getByRole('button', { name: 'OK', exact: true }).click()
    await expect(create).toHaveCount(0)
    await expect.poll(order).toEqual(['New opening:Early', 'A1:Act A', 'B1:Act B'])
    expect((await planning()).issues).toEqual([])
    await openPlan(h)
    await h.page.locator('.planning-view').getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(order).toEqual(['A1:Act A', 'B1:Act B'])
    expect((await planning()).acts[0]).toMatchObject({ name: 'Early', chapterGuids: [] })
  } finally { await h.close() }
})
